import { describe, expect, it } from "vitest";
import { formatIp } from "./ip";

describe("formatIp", () => {
  it.each([
    ["0000:0000:0000:0000:0000:0000:0000:0001", "::1"],
    ["0000:0000:0000:0000:0000:0000:0000:0000", "::"],
    ["2001:0db8:0000:0000:0000:ff00:0042:8329", "2001:db8::ff00:42:8329"],
    ["2001:db8:0:0:1:0:0:1", "2001:db8::1:0:0:1"],
    ["2001:0db8:0001:0000:0001:0001:0001:0001", "2001:db8:1:0:1:1:1:1"],
    ["::ffff:203.0.113.7", "203.0.113.7"],
    ["0000:0000:0000:0000:0000:ffff:203.0.113.7", "203.0.113.7"],
    ["203.0.113.7", "203.0.113.7"],
    ["::1", "::1"],
  ])("%s → %s", (input, expected) => {
    expect(formatIp(input)).toBe(expected);
  });

  it("passes null through", () => {
    expect(formatIp(null)).toBeNull();
  });
});
